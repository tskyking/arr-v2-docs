/** Local-only independent browser QA; no production endpoint accepted. */
import {chromium, expect} from '@playwright/test';
import {readFileSync,mkdirSync} from 'node:fs';
const path=process.env.PRODUCTION_QA_CREDENTIALS;
if(!path?.startsWith('/tmp/production-alpha-'))throw Error('Local fixture credential file required');
const credentials=JSON.parse(readFileSync(path,'utf8'));
const base=credentials.base;
if(!/^http:\/\/(127\.0\.0\.1|localhost):\d+\/api\/access-demo\/$/.test(base))throw Error('Local endpoint required');
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[];const results=[];
const captureDir=process.env.PRODUCTION_QA_SCREENSHOTS||'/tmp/production-qa-screenshots';mkdirSync(captureDir,{recursive:true});
async function page(){const p=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});p.on('pageerror',e=>errors.push(e.message));await p.goto(base+'production.html');return p;}
async function login(p,name,staff=false){if(staff)await p.locator('#staff-mode').click();await p.locator('[name=username]').fill(name);await p.locator('[name=password]').fill(staff?credentials.password:'abc@123');await p.getByRole('button',{name:'Sign in',exact:true}).click();await expect(p.locator('#identity')).toContainText(name);}
const api=async(p,route,input={})=>p.evaluate(async({route,input})=>{const response=await fetch('v2/production-'+route,{method:'POST',headers:{'Content-Type':'application/json','X-ARR-Request':'1'},body:JSON.stringify(input)});const body=await response.json();return{status:response.status,body};},{route,input});
try{
 const operator=await page();await login(operator,'person-1');
 await expect(operator.locator('[data-tab=arr]')).toBeVisible();
 await expect(operator.locator('[data-tab=dashboard]')).toHaveCount(0);
 await expect(operator.locator('body')).toContainText('Fictional demonstration');
 await operator.getByRole('button',{name:'Continue →',exact:true}).click();
 await operator.locator('[name=note]').fill('Independent browser QA fictional work note');
 await operator.getByRole('button',{name:'Continue →',exact:true}).click();
 await operator.getByRole('button',{name:'Submit check-in',exact:true}).click();
 await expect(operator.getByRole('heading',{name:'Thank you for sharing.'})).toBeVisible();
 results.push('Operator BOD UI submission');
 await operator.screenshot({path:captureDir+'/operator-confirmation.png',fullPage:true});
 await operator.getByRole('button',{name:'Another check-in',exact:true}).click();
 await operator.locator('[name=entryType]').selectOption('eod');
 await operator.getByRole('button',{name:'Continue →',exact:true}).click();
 await operator.locator('[name=recognition]').fill('QA recognition visible to management only');
 await operator.locator('[name=recognitionPeople]').selectOption('person-2');
 await operator.getByRole('button',{name:'Continue →',exact:true}).click();
 await operator.getByRole('button',{name:'Submit check-in',exact:true}).click();
 await expect(operator.getByRole('heading',{name:'Thank you for sharing.'})).toBeVisible();
 results.push('Operator EOD UI with optional recognition and blank counts');
 await operator.locator('[data-tab=prr]').click();
 await operator.getByRole('button',{name:'Continue →',exact:true}).click();
 await operator.locator('[name=categories][value=Ergonomic]').check();
 await operator.locator('[name=proposal]').fill('Browser QA fictional adjustable task lighting');
 await operator.locator('[name=expectedResult]').fill('Clearer view with less strain');
 await operator.getByRole('button',{name:'Continue →',exact:true}).click();
 await operator.getByRole('button',{name:'Submit proposal',exact:true}).click();
 await expect(operator.getByRole('heading',{name:'Thank you for sharing.'})).toBeVisible();
 results.push('PRR proposal through three-page UI');
 const own=(await api(operator,'list')).body.entries;
 const entry=own.find(r=>r.data.note==='Independent browser QA fictional work note');
 if(!entry)throw Error('Submitted BOD missing from own entries');
 const other=await page();await login(other,'person-2');
 if((await api(other,'detail',{id:entry.id})).status!==404)throw Error('Another operator can read first operator entry');
 results.push('Separate browser own-record isolation');
 const manager=await page();await login(manager,'manager',true);
 await expect(manager.locator('[data-tab=queue]')).toBeVisible();
 await manager.screenshot({path:captureDir+'/manager-queue.png',fullPage:true});
 const proposal=own.find(r=>r.data.proposal==='Browser QA fictional adjustable task lighting');
 if(!proposal)throw Error('PRR submission missing');
 await manager.locator(`[data-open="${proposal.id}"]`).click();
 await manager.locator('#proposal-update').fill('Refined browser QA trial with an adjustable light');
 await manager.locator('#publish-update').click();
 await expect(manager.locator('#notice')).toContainText('Saved.');
 if(!JSON.stringify((await api(operator,'detail',{id:proposal.id})).body).includes('Refined browser QA trial'))throw Error('Published update missing from worker view');
 results.push('Manager UI publishes worker-visible update');
 await manager.locator('#close-detail').click();

 let record=(await api(manager,'detail',{id:entry.id})).body.entry;
 let response=await api(manager,'action',{id:entry.id,revision:record.revision,action:'share',leadId:'reviewer'});
 if(response.status!==200)throw Error('Manager share failed: '+response.body.error);
 const lead=await page();await login(lead,'reviewer',true);
 await expect(lead.locator('[data-tab=dashboard]')).toHaveCount(0);
 if((await api(lead,'detail',{id:entry.id})).status!==200)throw Error('Assigned lead missing record');
 record=(await api(manager,'detail',{id:entry.id})).body.entry;
 await api(manager,'action',{id:entry.id,revision:record.revision,action:'retract',leadId:'reviewer'});
 if((await api(lead,'detail',{id:entry.id})).status!==404)throw Error('Retracted lead retains access');
 results.push('Separate staff contexts and lead share/retraction');
 await other.setViewportSize({width:390,height:844});
 if(await other.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2))throw Error('Mobile page has horizontal overflow');
 await other.screenshot({path:captureDir+'/operator-mobile.png',fullPage:true});
 results.push('Mobile form width');
 if(errors.length)throw Error('Browser errors: '+errors.join('; '));
 console.log(JSON.stringify({passed:results,pageErrors:errors,screenshots:captureDir},null,2));
}finally{await browser.close();}
